async function childOut(job, label) {
    assert.ok(job !== null, label + ': no job (anchor not matched exactly once)');
    const r = await job;
    assert.equal(r.error, null, label + ' child: ' + r.error);
    assert.ok(DONE.exec(r.stdout) !== null, label + ': driver did not reach its done marker (layouts DP)');
    return r.stdout;
}

/** The one in-region length of `name` from a child's output (asserts, fail closed). */
async function lengthOf(job, name, text, label) {
    const r = regionOf(text, R_MARKER);
    assert.ok(r !== null, label + ': RoaringSet marker missing / doubled, or not the last banner');
    const heads = parseHeaders(await childOut(job, label));
    assert.ok(heads !== null, label + ': a bytecode header without a length or a position');
    const n = rLength(heads, name, r);
    assert.ok(Number.isInteger(n) && n > 0, label + ': not exactly one ' + name + ' header inside the RoaringSet ' +
        'region [' + r[0] + ', ' + r[1] + '): ' + JSON.stringify(heads));
    return n;
}

async function measure() {
    const lengths = {};
    for (const name of NAMES) lengths[name] = await lengthOf(BC.get(name), name, SRC, name);
    assert.equal(Object.keys(lengths).length, NAMES.length, 'coverage floor: all 10 names measured');
    return lengths;
}
const MEASURED = measure();
MEASURED.catch(() => {});

/** Maglev's single-function inlining limit from this node's `--v8-options` (asserts: no parse = FAIL). */
async function maglevLimitOf() {
    const r = await V8_OPTS;
    assert.equal(r.error, null, '--v8-options child: ' + r.error);
    const limit = maglevLimit(r.stdout);
    assert.ok(Number.isInteger(limit) && limit > 0, 'could not parse --max-maglev-inlined-bytecode-size from --v8-options');
    return limit;
}

function pick(lengths, names) {
    const o = {};
    for (const n of names) o[n] = lengths[n];
    return o;
}

