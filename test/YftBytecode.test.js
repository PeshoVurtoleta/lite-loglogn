/**
 * @zakkster/lite-loglogn -- YFastTrie BYTECODE BUDGET gate (plan G2-7, C-17,
 * DETERMINISTIC).
 *
 * Every YFastTrie hot method and in-bucket helper (has add delete successor
 * predecessor min max _loc _lb) must have a V8 `Bytecode length` <= 460 B
 * (BUDGET; Node's `--max-inlined-bytecode-size` default, read from
 * `node --v8-options` and required to be >= BUDGET, so "<= BUDGET" still means
 * "inlinable" on the running Node).
 *
 * Method: one child per name, `node --print-bytecode --print-bytecode-filter=<name>`
 * on a driver (DRIVER below, run with `-e`) that imports ../LogLogN.js and
 * exercises ONLY YFastTrie -- splits and merges included, so the inner
 * XFastTrie `_x` compiles its own add / delete. Every printed header is
 * attributed by its first source position to a region of the loaded source
 * (a `// --- <Member>` marker to the next `// --- ` marker or EOF):
 * - Y = `// --- YFastTrie (0.4.0)` (the last marker, so it runs to EOF);
 * - X = `// --- XFastTrie (0.3.0)` (the inner trie's own methods).
 * Fail closed (GATE TEETH): every header must carry the filtered name, a
 * parseable length and a source position; EXACTLY ONE lies in Y; every other
 * one lies in X (an inner-trie method of the same name). A header in neither
 * region (StratifiedBitset, the preamble), a second Y header, a header with no
 * length or no position = FAIL, never a skip. The driver's own stdout marker
 * proves it ran its workload (with >= 1 split and >= 1 merge) to the end.
 *
 * Must-fail controls (each its own test):
 * - PADDED: YFastTrie#has padded with 40 copies of `this._x._q[0] = x;`
 *   (behaviour unchanged), loaded from a data: URL, is found once, in Y, and is
 *   reported OVER the budget.
 * - BOTH: a driver that also calls StratifiedBitset#has prints a `has` header
 *   outside both regions, which the parser rejects.
 * - parser unit rows: good / missing / doubled in Y / no length / no position /
 *   wrong name / outside both regions / X only / NaN budget.
 *
 * Every child has its own 60 s SIGKILL timeout; all start at module load.
 */

import test from 'node:test';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const T = { timeout: 120000 };
const CHILD_MS = 60000;
const BUDGET = 460;
const SRC_PATH = fileURLToPath(new URL('../LogLogN.js', import.meta.url));
const SRC_URL = pathToFileURL(SRC_PATH).href;
const SRC = readFileSync(SRC_PATH, 'utf8');
const NAMES = ['has', 'add', 'delete', 'successor', 'predecessor', 'min', 'max', '_loc', '_lb'];
// names the inner XFastTrie must also compile under this workload (proves the X allowance is live)
const INNER = ['add', 'delete'];
const Y_MARKER = '// --- YFastTrie (0.4.0)';
const X_MARKER = '// --- XFastTrie (0.3.0)';
const HEAD = '[generated bytecode for function: ';
const PAD_FROM = '        const j = this._lb(o, s);\n        return j < s && this._bk[o + j] === x;\n';
const PAD_TO = '        this._x._q[0] = x;\n'.repeat(40) + PAD_FROM;
const DONE = /^yft-bytecode-driver done size=(\d+) splits=(\d+) merges=(\d+) acc=(-?\d+)$/m;
const FINAL_SIZE = 512;

// The child workload. argv[1] = module URL or '-' (source on stdin);
// argv[2] = 'yft' (YFastTrie only) or 'both' (also StratifiedBitset#has).
// 2048 adds (K = 40 -> splits), 3 of 4 deleted (buckets fall to <= h -> merges).
const DRIVER = `
const { readFileSync } = await import('node:fs');
const arg = process.argv[1];
const url = arg === '-' ?
    'data:text/javascript;base64,' + Buffer.from(readFileSync(0, 'utf8'), 'utf8').toString('base64') : arg;
const { YFastTrie, StratifiedBitset } = await import(url);
const t = new YFastTrie(1048576, 4096);
let acc = 0;
for (let i = 0; i < 2048; i++) t.add(i * 97);
for (let i = 0; i < 256; i++) {
    acc += t.has(i * 31) ? 1 : 0;
    acc += t.successor(i * 613 + 5) ?? 0;
    acc += t.predecessor(i * 773 + 7) ?? 0;
    acc += t.min() ?? 0;
    acc += t.max() ?? 0;
}
for (let i = 0; i < 2048; i++) {
    if ((i & 3) !== 0 && !t.delete(i * 97)) throw new Error('driver: delete of a present key returned false');
}
for (let i = 0; i < 64; i++) acc += t.has(i * 388) ? 1 : 0;
if (process.argv[2] === 'both') acc += new StratifiedBitset(1024).add(3).has(3) ? 1 : 0;
process.stdout.write('yft-bytecode-driver done size=' + t.size + ' splits=' + t._n[0] +
    ' merges=' + t._n[1] + ' acc=' + acc + '\\n');
`;

// --- helpers (pure; unit-tested below) ------------------------------------------

/** [start, end) of the region opened by `marker` in `text`, or null (marker missing / doubled). */
function regionOf(text, marker) {
    const a = text.indexOf(marker);
    if (a < 0 || text.indexOf(marker, a + 1) >= 0) return null;
    const b = text.indexOf('\n// --- ', a + marker.length);
    return [a, b < 0 ? text.length : b];
}

/**
 * Every bytecode header in `text` as { name, len, pos } (pos = the first
 * statement position of that function's own block); null if ANY header lacks
 * a length line or a position (fail closed: an unparseable header is never
 * dropped).
 */
function parseHeaders(text) {
    const blocks = text.split(HEAD);
    const out = [];
    for (let i = 1; i < blocks.length; i++) {
        const h = /^(\S*) [^\]\n]*\]\s*\nBytecode length: (\d+)\n/.exec(blocks[i]);
        const p = /^\s*(\d+) S> /m.exec(blocks[i]);
        if (h === null || p === null) return null;
        out.push({ name: h[1], len: Number(h[2]), pos: Number(p[1]) });
    }
    return out;
}

/**
 * The length of the ONE header named `name` whose position lies in y = [lo, hi);
 * every other header must carry `name` and lie in x; else NaN.
 */
function yLength(heads, name, y, x) {
    if (heads === null || y === null || x === null) return NaN;
    let n = NaN;
    let inY = 0;
    for (const r of heads) {
        if (r.name !== name || !Number.isInteger(r.len) || !Number.isInteger(r.pos)) return NaN;
        if (r.pos >= y[0] && r.pos < y[1]) {
            inY++;
            n = r.len;
        } else if (!(r.pos >= x[0] && r.pos < x[1])) {
            return NaN;
        }
    }
    return inY === 1 ? n : NaN;
}

/** Names whose length is not a finite number <= budget (fail closed). */
function overBudget(lengths, budget) {
    const over = [];
    for (const name of Object.keys(lengths)) {
        const n = lengths[name];
        if (!Number.isFinite(budget) || !Number.isFinite(n) || !(n <= budget)) over.push(name);
    }
    return over;
}

/** Fail-closed parse of the inlining cap from `node --v8-options` text. */
function parseCap(text) {
    const m = /--max-inlined-bytecode-size=(\d+)\b/.exec(text);
    if (m === null) return NaN;
    const n = Number(m[1]);
    return Number.isInteger(n) && n > 0 ? n : NaN;
}

function runChild(args, input) {
    return new Promise((resolve) => {
        const cp = execFile(process.execPath, args, {
            encoding: 'utf8', timeout: CHILD_MS, killSignal: 'SIGKILL', maxBuffer: 1 << 26,
        }, (err, stdout, stderr) => {
            resolve({
                error: err ? String(err.message) + (err.signal ? ' signal ' + err.signal : '') +
                    ' | stderr: ' + String(stderr).slice(0, 2048) : null,
                stdout,
            });
        });
        if (input !== undefined) cp.stdin.end(input);
        else cp.stdin.end();
    });
}

function bytecodeChild(name, srcArg, mode, input) {
    return runChild(['--print-bytecode', '--print-bytecode-filter=' + name, '--input-type=module',
        '-e', DRIVER, srcArg, mode], input);
}

// --- all children start now, in parallel ---------------------------------------

const PAD_COUNT = SRC.split(PAD_FROM).length - 1;
const PADDED = PAD_COUNT === 1 ? SRC.replace(PAD_FROM, () => PAD_TO) : null;
const CAP_JOB = runChild(['--v8-options']);
const BC = new Map();
for (const name of NAMES) BC.set(name, bytecodeChild(name, SRC_URL, 'yft'));
const PAD_JOB = PADDED === null ? null : bytecodeChild('has', '-', 'yft', PADDED);
const BOTH_JOB = bytecodeChild('has', SRC_URL, 'both');

async function childOut(job, label) {
    const r = await job;
    assert.equal(r.error, null, label + ' child: ' + r.error);
    const d = DONE.exec(r.stdout);
    assert.ok(d !== null, label + ': driver did not reach its done marker');
    assert.equal(Number(d[1]), FINAL_SIZE, label + ': driver final size');
    assert.ok(Number(d[2]) >= 1 && Number(d[3]) >= 1, label + ': driver must split and merge: ' + d[0]);
    return r.stdout;
}

// --- gate ------------------------------------------------------------------------

test('G2-7 every YFastTrie hot method / helper has one Y-region header, extras only in X, <= 460 B',
    T, async (t) => {
        const cap = parseCap((await CAP_JOB).stdout);
        assert.ok(Number.isInteger(cap), '--max-inlined-bytecode-size default not parseable');
        assert.ok(BUDGET <= cap, 'BUDGET ' + BUDGET + ' exceeds the inlining cap ' + cap);
        const y = regionOf(SRC, Y_MARKER);
        const x = regionOf(SRC, X_MARKER);
        assert.ok(y !== null && x !== null, 'YFastTrie / XFastTrie marker missing or doubled in LogLogN.js');
        assert.equal(y[1], SRC.length, 'YFastTrie is the last member: its region must run to EOF');
        const lengths = {};
        const inner = {};
        for (const name of NAMES) {
            const heads = parseHeaders(await childOut(BC.get(name), name));
            assert.ok(heads !== null, name + ': a bytecode header without a length or a position');
            const n = yLength(heads, name, y, x);
            assert.ok(Number.isInteger(n) && n > 0, name + ': not exactly one YFastTrie header in [' +
                y[0] + ', ' + y[1] + ') with every other in XFastTrie [' + x[0] + ', ' + x[1] + '): ' +
                JSON.stringify(heads));
            lengths[name] = n;
            inner[name] = heads.length - 1;
        }
        // coverage floor: every one of the 9 names measured, none skipped
        assert.equal(Object.keys(lengths).length, NAMES.length);
        // the X allowance is exercised, not vacuous: the inner trie compiled its own add / delete
        for (const name of INNER) assert.ok(inner[name] >= 1, name + ': no inner XFastTrie header seen');
        t.diagnostic('budget=' + BUDGET + ' cap=' + cap + ' ' + JSON.stringify(lengths) +
            ' innerHeaders=' + JSON.stringify(inner));
        assert.deepEqual(overBudget(lengths, BUDGET), [], 'over ' + BUDGET + ' B: ' + JSON.stringify(lengths));
    });

// --- must-fail controls ----------------------------------------------------------

test('G2-7 control: a padded YFastTrie#has (> 460 B) is found in Y and reported over', T, async (t) => {
    assert.equal(PAD_COUNT, 1, 'pad anchor must occur exactly once in LogLogN.js');
    const y = regionOf(PADDED, Y_MARKER);
    const x = regionOf(PADDED, X_MARKER);
    assert.ok(y !== null && x !== null);
    const heads = parseHeaders(await childOut(PAD_JOB, 'padded has'));
    const n = yLength(heads, 'has', y, x);
    assert.ok(Number.isInteger(n), 'padded has not found exactly once in Y');
    t.diagnostic('padded has=' + n);
    assert.ok(n > BUDGET, 'padded has ' + n + ' must exceed ' + BUDGET);
    assert.deepEqual(overBudget({ has: n }, BUDGET), ['has']);
});

test('G2-7 control: also calling StratifiedBitset#has puts a header outside both regions', T, async () => {
    const y = regionOf(SRC, Y_MARKER);
    const x = regionOf(SRC, X_MARKER);
    const heads = parseHeaders(await childOut(BOTH_JOB, 'both'));
    assert.ok(heads !== null);
    assert.equal(heads.length, 2, 'both drivers must compile two has bodies');
    const outside = heads.filter((r) => !(r.pos >= y[0] && r.pos < y[1]) && !(r.pos >= x[0] && r.pos < x[1]));
    assert.equal(outside.length, 1, 'StratifiedBitset#has must sit outside Y and X');
    assert.ok(Number.isNaN(yLength(heads, 'has', y, x)), 'a header outside both regions must not parse');
});

test('G2-7 control: parser and budget fail closed', T, () => {
    const row = (name, len, pos) => HEAD + name + ' (0x1 <SharedFunctionInfo ' + name + '>)]\n' +
        'Bytecode length: ' + len + '\nParameter count 2\n  ' + pos + ' S> 0x1 @    0 : 0b 03             Ldar a0\n';
    const Y = [1000, 2000];
    const X = [100, 1000];
    const good = row('add', 296, 1500) + row('add', 300, 500);
    assert.deepEqual(parseHeaders(good), [{ name: 'add', len: 296, pos: 1500 }, { name: 'add', len: 300, pos: 500 }]);
    assert.equal(yLength(parseHeaders(good), 'add', Y, X), 296, 'good: one Y + one X');
    assert.equal(yLength(parseHeaders(row('has', 120, 1000)), 'has', Y, X), 120, 'good: Y only, at region start');
    assert.deepEqual(parseHeaders(''), []);
    assert.ok(Number.isNaN(yLength(parseHeaders(''), 'has', Y, X)), 'missing header');
    assert.ok(Number.isNaN(yLength(parseHeaders(row('add', 300, 500)), 'add', Y, X)), 'X only, no Y header');
    assert.ok(Number.isNaN(yLength(parseHeaders(row('has', 120, 1500) + row('has', 121, 1600)), 'has', Y, X)),
        'duplicate header in Y');
    const noLen = row('has', 120, 1500).replace('Bytecode length: 120\n', '');
    assert.equal(parseHeaders(noLen), null, 'header with no size');
    assert.equal(parseHeaders(good + noLen), null, 'one unparseable header poisons the whole parse');
    assert.ok(Number.isNaN(yLength(parseHeaders(noLen), 'has', Y, X)));
    assert.equal(parseHeaders(row('has', 120, 1500).replace(' S> ', ' E> ')), null, 'no position');
    assert.equal(parseHeaders(row('has', 'NaN', 1500)), null, 'non-numeric size');
    assert.ok(Number.isNaN(yLength(parseHeaders(row('has', 120, 1500)), 'add', Y, X)), 'wrong name');
    assert.ok(Number.isNaN(yLength(parseHeaders(row('has', 120, 1500) + row('add', 300, 500)), 'has', Y, X)),
        'mixed names');
    assert.ok(Number.isNaN(yLength(parseHeaders(row('has', 120, 1500) + row('has', 90, 50)), 'has', Y, X)),
        'extra header below X (outside both regions)');
    assert.ok(Number.isNaN(yLength(parseHeaders(row('has', 120, 2000)), 'has', Y, X)), 'position at Y end');
    assert.ok(Number.isNaN(yLength(parseHeaders(good), 'add', null, X)), 'null region');
    assert.ok(Number.isNaN(yLength(null, 'add', Y, X)), 'null parse');
    assert.deepEqual(overBudget({ has: 460, add: 461, min: NaN }, BUDGET), ['add', 'min']);
    assert.deepEqual(overBudget({ has: 1 }, NaN), ['has']);
    assert.ok(Number.isNaN(parseCap('--max-inlined-bytecode-size-cumulative=920')));
    assert.equal(regionOf('x', Y_MARKER), null);
    assert.equal(regionOf(Y_MARKER + Y_MARKER, Y_MARKER), null);
    assert.deepEqual(regionOf('a\n' + Y_MARKER + ' b\n// --- next', Y_MARKER), [2, 2 + Y_MARKER.length + 2]);
    assert.deepEqual(regionOf('a\n' + Y_MARKER + ' b', Y_MARKER), [2, 2 + Y_MARKER.length + 2], 'last marker -> EOF');
});
