/**
 * @zakkster/lite-loglogn -- XFastTrie BYTECODE BUDGET gate (plan E14,
 * DETERMINISTIC).
 *
 * Every XFastTrie hot method and hot helper (has add delete successor
 * predecessor min max _slot _put _near fmix32) must have a V8 `Bytecode length`
 * <= 460 B (BUDGET; Node's `--max-inlined-bytecode-size` default, read from
 * `node --v8-options` and required to be >= BUDGET, so "<= BUDGET" still means
 * "inlinable" on the running Node).
 *
 * Method: one child per name, `node --print-bytecode --print-bytecode-filter=<name>`
 * on a driver (DRIVER below, run with `-e`) that imports ../LogLogN.js and
 * exercises ONLY XFastTrie. StratifiedBitset shares the names has / add /
 * delete / successor / predecessor / min / max; V8 compiles lazily, so a
 * StratifiedBitset method is never compiled (never printed) unless it is
 * called. Fail closed (GATE TEETH): each name must print EXACTLY ONE bytecode
 * header, carrying that name, a parseable length and a first source position
 * inside the XFastTrie region of the loaded source (from the
 * `// --- XFastTrie (0.3.0)` marker to the next `// --- ` marker or EOF).
 * Missing, ambiguous or out-of-region = FAIL, never a skip; the driver's own
 * stdout marker proves it ran its workload to the end.
 *
 * Must-fail controls (each its own test):
 * - PADDED: `has` padded with 40 copies of `this._q[0] = x;` (behaviour
 *   unchanged), loaded from a data: URL, is found once, in region, and is
 *   reported OVER the budget.
 * - BOTH: a driver that also calls StratifiedBitset#has prints two `has`
 *   headers, which the parser rejects as ambiguous.
 * - parser unit rows: empty / doubled / wrong name / out-of-region / NaN.
 *
 * Every child has its own 60 s SIGKILL timeout; all start at module load.
 */

import test from 'node:test';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const T = { timeout: 120000 };
const CHILD_MS = 60000;
const BUDGET = 460;
const SRC_PATH = fileURLToPath(new URL('../LogLogN.js', import.meta.url));
const SRC_URL = pathToFileURL(SRC_PATH).href;
const SRC = readFileSync(SRC_PATH, 'utf8');
const NAMES = ['has', 'add', 'delete', 'successor', 'predecessor', 'min', 'max',
    '_slot', '_put', '_near', 'fmix32'];
const MARKER = '// --- XFastTrie (0.3.0)';
const PAD_FROM = '        this._q[0] = x;\n        return this._slot(this._w) >= 0;\n';
const PAD_TO = '        this._q[0] = x;\n' + '        this._q[0] = x;\n'.repeat(40) +
    '        return this._slot(this._w) >= 0;\n';
const DONE = /^xft-bytecode-driver done size=(\d+) acc=(-?\d+)$/m;

// The child workload. argv[1] = module URL or '-' (source on stdin);
// argv[2] = 'xft' (XFastTrie only) or 'both' (also StratifiedBitset#has).
const DRIVER = `
const { readFileSync } = await import('node:fs');
const arg = process.argv[1];
const url = arg === '-' ?
    'data:text/javascript;base64,' + Buffer.from(readFileSync(0, 'utf8'), 'utf8').toString('base64') : arg;
const { XFastTrie, StratifiedBitset } = await import(url);
const t = new XFastTrie(1048576, 1024);
let acc = 0;
for (let i = 0; i < 64; i++) {
    t.add(i * 977);
    t.add(i * 977 + 1);
    acc += t.has(i * 31) ? 1 : 0;
    acc += t.successor(i * 13 + 5) ?? 0;
    acc += t.predecessor(i * 4093 + 7) ?? 0;
    acc += t.min() ?? 0;
    acc += t.max() ?? 0;
    if (!t.delete(i * 977 + 1)) throw new Error('driver: delete of a present key returned false');
}
if (process.argv[2] === 'both') acc += new StratifiedBitset(1024).add(3).has(3) ? 1 : 0;
process.stdout.write('xft-bytecode-driver done size=' + t.size + ' acc=' + acc + '\\n');
`;

// --- helpers (pure; unit-tested below) ------------------------------------------

/** [start, end) of the XFastTrie region in `text`, or null (marker missing / doubled). */
function regionOf(text) {
    const a = text.indexOf(MARKER);
    if (a < 0 || text.indexOf(MARKER, a + 1) >= 0) return null;
    const b = text.indexOf('\n// --- ', a + MARKER.length);
    return [a, b < 0 ? text.length : b];
}

/**
 * Exactly one bytecode header for a function named `name`, its length, and a
 * first source position in [lo, hi); else NaN.
 */
function parseLength(text, name, lo, hi) {
    const headers = text.split('[generated bytecode for function: ').length - 1;
    const re = /\[generated bytecode for function: (\S*) [^\]]*\]\s*\nBytecode length: (\d+)\n[\s\S]*?^\s*(\d+) S> /gm;
    const hits = [];
    let m;
    while ((m = re.exec(text)) !== null) hits.push(m);
    if (headers !== 1 || hits.length !== 1 || hits[0][1] !== name) return NaN;
    const pos = Number(hits[0][3]);
    if (!(pos >= lo && pos < hi)) return NaN;
    return Number(hits[0][2]);
}

/** Names whose length is not a finite number <= budget (fail closed). */
function overBudget(lengths, budget) {
    const over = [];
    for (const name of Object.keys(lengths)) {
        const n = lengths[name];
        if (!Number.isFinite(budget) || !Number.isFinite(n) || !(n <= budget)) over.push(name);
    }
    return over;
}

/** Fail-closed parse of the inlining cap from `node --v8-options` text. */
function parseCap(text) {
    const m = /--max-inlined-bytecode-size=(\d+)\b/.exec(text);
    if (m === null) return NaN;
    const n = Number(m[1]);
    return Number.isInteger(n) && n > 0 ? n : NaN;
}

function runChild(args, input) {
    return new Promise((resolve) => {
        const cp = execFile(process.execPath, args, {
            encoding: 'utf8', timeout: CHILD_MS, killSignal: 'SIGKILL', maxBuffer: 1 << 26,
        }, (err, stdout, stderr) => {
            resolve({
                error: err ? String(err.message) + (err.signal ? ' signal ' + err.signal : '') +
                    ' | stderr: ' + String(stderr).slice(0, 2048) : null,
                stdout,
            });
        });
        if (input !== undefined) cp.stdin.end(input);
        else cp.stdin.end();
    });
}

function bytecodeChild(name, srcArg, mode, input) {
    return runChild(['--print-bytecode', '--print-bytecode-filter=' + name, '--input-type=module',
        '-e', DRIVER, srcArg, mode], input);
}

// --- all children start now, in parallel ---------------------------------------

const PAD_COUNT = SRC.split(PAD_FROM).length - 1;
const PADDED = PAD_COUNT === 1 ? SRC.replace(PAD_FROM, () => PAD_TO) : null;
const CAP_JOB = runChild(['--v8-options']);
const BC = new Map();
for (const name of NAMES) BC.set(name, bytecodeChild(name, SRC_URL, 'xft'));
const PAD_JOB = PADDED === null ? null : bytecodeChild('has', '-', 'xft', PADDED);
const BOTH_JOB = bytecodeChild('has', SRC_URL, 'both');

async function childOut(job, label) {
    const r = await job;
    assert.equal(r.error, null, label + ' child: ' + r.error);
    const d = DONE.exec(r.stdout);
    assert.ok(d !== null, label + ': driver did not reach its done marker');
    assert.equal(Number(d[1]), 64, label + ': driver final size');
    return r.stdout;
}

// --- gate ------------------------------------------------------------------------

test('E14 every XFastTrie hot method / helper is found once, in region, <= 460 B', T, async (t) => {
    const cap = parseCap((await CAP_JOB).stdout);
    assert.ok(Number.isInteger(cap), '--max-inlined-bytecode-size default not parseable');
    assert.ok(BUDGET <= cap, 'BUDGET ' + BUDGET + ' exceeds the inlining cap ' + cap);
    const reg = regionOf(SRC);
    assert.ok(reg !== null, 'XFastTrie marker missing or doubled in LogLogN.js');
    const lengths = {};
    for (const name of NAMES) {
        const out = await childOut(BC.get(name), name);
        const n = parseLength(out, name, reg[0], reg[1]);
        assert.ok(Number.isInteger(n) && n > 0,
            name + ': XFastTrie bytecode not found exactly once inside [' + reg[0] + ', ' + reg[1] + ')');
        lengths[name] = n;
    }
    // coverage floor: every one of the 11 names measured, none skipped
    assert.equal(Object.keys(lengths).length, NAMES.length);
    t.diagnostic('budget=' + BUDGET + ' cap=' + cap + ' ' + JSON.stringify(lengths));
    assert.deepEqual(overBudget(lengths, BUDGET), [], 'over ' + BUDGET + ' B: ' + JSON.stringify(lengths));
});

// --- must-fail controls ----------------------------------------------------------

test('E14 control: a padded has (> 460 B) is found in region and reported over', T, async (t) => {
    assert.equal(PAD_COUNT, 1, 'pad anchor must occur exactly once in LogLogN.js');
    const reg = regionOf(PADDED);
    assert.ok(reg !== null);
    const out = await childOut(PAD_JOB, 'padded has');
    const n = parseLength(out, 'has', reg[0], reg[1]);
    assert.ok(Number.isInteger(n), 'padded has not found exactly once in region');
    t.diagnostic('padded has=' + n);
    assert.ok(n > BUDGET, 'padded has ' + n + ' must exceed ' + BUDGET);
    assert.deepEqual(overBudget({ has: n }, BUDGET), ['has']);
});

test('E14 control: also calling StratifiedBitset#has makes the has match ambiguous', T, async () => {
    const reg = regionOf(SRC);
    const out = await childOut(BOTH_JOB, 'both');
    assert.equal(out.split('[generated bytecode for function: has ').length - 1, 2,
        'both drivers must compile two has bodies');
    assert.ok(Number.isNaN(parseLength(out, 'has', reg[0], reg[1])), 'ambiguous match must not parse');
});

test('E14 control: parser and budget fail closed', T, () => {
    const one = '[generated bytecode for function: has (0x1 <SharedFunctionInfo has>)]\n' +
        'Bytecode length: 67\nParameter count 2\n  100 S> 0x1 @    0 : 0b 03             Ldar a0\n';
    assert.equal(parseLength(one, 'has', 50, 200), 67);
    assert.ok(Number.isNaN(parseLength('', 'has', 0, 1e9)), 'missing');
    assert.ok(Number.isNaN(parseLength(one + one, 'has', 50, 200)), 'doubled');
    assert.ok(Number.isNaN(parseLength(one, 'add', 50, 200)), 'wrong name');
    assert.ok(Number.isNaN(parseLength(one, 'has', 101, 200)), 'position below region');
    assert.ok(Number.isNaN(parseLength(one, 'has', 0, 100)), 'position at region end');
    assert.ok(Number.isNaN(parseLength(one.replace('  100 S>', '  100 E>'), 'has', 0, 1e9)), 'no position');
    assert.deepEqual(overBudget({ has: 460, add: 461, min: NaN }, BUDGET), ['add', 'min']);
    assert.deepEqual(overBudget({ has: 1 }, NaN), ['has']);
    assert.ok(Number.isNaN(parseCap('--max-inlined-bytecode-size-cumulative=920')));
    assert.equal(regionOf('x'), null);
    assert.equal(regionOf(MARKER + MARKER), null);
    assert.deepEqual(regionOf('a\n' + MARKER + ' b\n// --- next'), [2, 2 + MARKER.length + 2]);
});
