/**
 * @zakkster/lite-loglogn -- RoaringSet BYTECODE SIZE gate (plan G4 tasks 5-6,
 * assertion A-4; SPEC C-1 / C-6 / C-9; DETERMINISTIC), in the shape of
 * VebBytecode.test.js.
 *
 * RoaringSet's hot methods (has add delete successor predecessor min max), its
 * two bitmap scan helpers (_bmpNextGEQ _bmpPrevLEQ) and the container search
 * _lb16 are measured with V8
 * `Bytecode length`: one child per name, `node --print-bytecode
 * --print-bytecode-filter=<name>` on a driver that imports ../LogLogN.js and
 * exercises ONLY RoaringSet, on a DIRECT instance (U = 2^24) and a PAGED one
 * (U = 2^32, maxPages 16, pageBits 8). Both layouts run the same class body (the
 * layout is per-instance data, `_mi(c)`), so there is no per-layout name. Every
 * chunk kind is built (single, small array, large array, bitmap, large runs,
 * small runs, full) and queried, and bitmap mins / maxes are deleted (the
 * re-derive callers of the helpers). Each printed header is attributed by its
 * first source position to the RoaringSet region (`// --- RoaringSet (0.6.0)` to
 * EOF; it must be the LAST banner, else the region is null and every name fails
 * closed); EXACTLY ONE header per name must lie there and none outside it.
 *
 * Policy:
 * - SIZE pins (exact lengths) are keyed to V8 major.minor 14.6 (cut once,
 *   2026-11-05, node v26.8.2, V8 14.6.202.34-node.28, after the P-5 shrink,
 *   evidence .handoff/evidence/roaring-g4-u5.md). On any other V8 the pin test
 *   FAILS CLOSED (no pin = unverified: re-measure and add a row), never skips.
 * - _lb16 <= Maglev's single-function inlining limit, parsed from the default of
 *   --max-maglev-inlined-bytecode-size in `node --v8-options` on ANY V8 (no parse
 *   = FAIL). Its 91 B pin is the sign-shift branchless body (PLAN roaring-search
 *   addendum A-A1), measured against that ruling's figure, never read back from a
 *   run here.
 * - _lb16 <= 94 B on ANY V8 (A-6, derivation at LB16_CEILING): a bytecode-size
 *   gate, the deterministic proxy for the caller's cumulative inlining budget. It
 *   is not a JIT-decision gate (LEDGER Law 14): no test here reads what V8 inlined.
 * - On ANY V8: has / min / max <= 460 B (BUDGET, the Node default
 *   --max-inlined-bytecode-size); add / delete / successor / predecessor > 460 B
 *   (documented over the inlining limit, ADR 0010 P-5 and the .d.ts boxing note:
 *   this check backs that claim, it is not a defect of the engine).
 *
 * Must-fail controls (each its own test; mutated copies are written to an
 * mkdtemp dir, every anchor matched exactly once or the control fails):
 * - PADDED: RoaringSet#has padded with 40 `void this._u;` is found once, in the
 *   region, with a size != and > its pin.
 * - BOTH: a driver that also calls vEBTree#has prints a `has` header outside the
 *   RoaringSet region, which the parser rejects.
 * - DEADEXIT: `if (i >= 2048) return -1;` re-inserted into _bmpNextGEQ (the exit
 *   the P-5 shrink removed) makes it larger than its pin.
 * - CTXREF: a cold `toString() { return RoaringSet.name; }` (a class-body
 *   reference to RoaringSet, forbidden by C-6) moves the add / delete pins.
 * - GUARD: `if (len === 0) return 0;` inserted at the top of _lb16 exceeds both its
 *   pin and the 94 B ceiling: the guard R-4 rejects, its diagnostic the measured cost.
 *   On the 91 B body it reads exactly the Maglev limit, so it no longer proves that row.
 * - LBPAD: _lb16 padded past 100 B exceeds the pin, the 94 B ceiling and the Maglev limit.
 * - parser unit rows (good / missing / doubled / no length / no position /
 *   wrong name / outside region / NaN budget / a banner after the marker / the
 *   Maglev limit line).
 *
 * Children run at most CAP at a time; each has its own SIGKILL timeout, which
 * starts when it is spawned (queueing does not consume it).
 */

