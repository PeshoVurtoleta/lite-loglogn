/**
 * @zakkster/lite-loglogn -- vEBTree BYTECODE SIZE gate (plan G2-7, C-14 / C-21,
 * DETERMINISTIC), in the shape of YftBytecode.test.js.
 *
 * vEBTree's hot methods (has add delete successor predecessor min max) are
 * measured with V8 `Bytecode length`: one child per name, `node --print-bytecode
 * --print-bytecode-filter=<name>` on a driver that imports ../LogLogN.js and
 * exercises ONLY vEBTree (U = 2^16, 2^24 + 1, 2^28, 200: leaf, depth-1 and
 * depth-2 paths). Each printed header is attributed by its first source position
 * to the vEB region (`// --- vEBTree (0.5.0)` to EOF); EXACTLY ONE header per
 * name must lie there and none outside it (fail closed, never a skip).
 *
 * Policy:
 * - SIZE pins (exact lengths) are keyed to V8 major.minor 14.6 (measured
 *   2026-11-03, node v26.8.2, V8 14.6.202.34-node.28, evidence
 *   .handoff/evidence/veb-g2-b0-2026-11-03.md). On any other V8 the pin test
 *   FAILS CLOSED (no pin = unverified: re-measure and add a row), it never skips.
 * - On ANY V8, delete / successor / predecessor must be > 460 B (BUDGET, the
 *   Node default --max-inlined-bytecode-size): they are never inlined, which is
 *   the boxing caveat C-11 (a computed double returned across a call boundary).
 *
 * Must-fail controls (each its own test):
 * - PADDED: vEBTree#has padded with 40 harmless statements is found once, in
 *   the vEB region, and its size is NOT the pinned 218 (pin fails) and > 218.
 * - BOTH: a driver that also calls StratifiedBitset#has prints a `has` header
 *   outside the vEB region, which the parser rejects.
 * - parser unit rows (good / missing / doubled / no length / no position /
 *   wrong name / outside region / NaN budget).
 */

import test from 'node:test';
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const T = { timeout: 120000 };
const CHILD_MS = 60000;
const BUDGET = 460;
const SRC_PATH = fileURLToPath(new URL('../LogLogN.js', import.meta.url));
const SRC_URL = pathToFileURL(SRC_PATH).href;
const SRC = readFileSync(SRC_PATH, 'utf8');
const NAMES = ['has', 'add', 'delete', 'successor', 'predecessor', 'min', 'max'];
const NEVER_INLINED = ['delete', 'successor', 'predecessor'];
const V_MARKER = '\n// --- vEBTree (0.5.0)';
const HEAD = '[generated bytecode for function: ';
// Pins by V8 major.minor (spec: evidence veb-g2-b0-2026-11-03.md, not re-derived from this run).
const PINS = {
    '14.6': { has: 218, add: 450, delete: 1285, successor: 850, predecessor: 838, min: 114, max: 133 },
};
const PAD_FROM = '            if (x === mn || x === mx) return true;\n';
const PAD_TO = PAD_FROM + '        this._g[0] = this._g[0];\n'.repeat(40);
const DONE = /^veb-bytecode-driver done acc=(\d+)$/m;

const DRIVER = `
const { readFileSync } = await import('node:fs');
const arg = process.argv[1];
const url = arg === '-' ?
    'data:text/javascript;base64,' + Buffer.from(readFileSync(0, 'utf8'), 'utf8').toString('base64') : arg;
const { vEBTree, StratifiedBitset } = await import(url);
let acc = 0;
for (const U of [65536, 16777217, 268435456, 200]) {
    const t = new vEBTree(U);
    for (let i = 0; i < 3000; i++) t.add((i * 40503 + 7) % U);
    for (let i = 0; i < 3000; i++) {
        acc += t.has((i * 977) % U) ? 1 : 0;
        acc += t.successor((i * 6131) % U) ?? 0;
        acc += t.predecessor((i * 7919) % U) ?? 0;
        acc += t.min() ?? 0;
        acc += t.max() ?? 0;
    }
    for (let i = 0; i < 3000; i++) if ((i & 1) === 0) t.delete((i * 40503 + 7) % U);
}
if (process.argv[2] === 'both') acc += new StratifiedBitset(1024).add(3).has(3) ? 1 : 0;
process.stdout.write('veb-bytecode-driver done acc=' + (acc >>> 0) + '\\n');
`;

// --- helpers (pure; unit-tested below) ------------------------------------------

/** [start, end) = marker to EOF, or null (marker missing / doubled). */
function regionOf(text, marker) {
    const a = text.indexOf(marker);
    if (a < 0 || text.indexOf(marker, a + 1) >= 0) return null;
    return [a, text.length];
}

/** Every header as { name, len, pos }; null if ANY header lacks a length or a position. */
function parseHeaders(text) {
    const blocks = text.split(HEAD);
    const out = [];
    for (let i = 1; i < blocks.length; i++) {
        const h = /^(\S*) [^\]\n]*\]\s*\nBytecode length: (\d+)\n/.exec(blocks[i]);
        const p = /^\s*(\d+) S> /m.exec(blocks[i]);
        if (h === null || p === null) return null;
        out.push({ name: h[1], len: Number(h[2]), pos: Number(p[1]) });
    }
    return out;
}

/** Length of the ONE header named `name`, all headers inside region v; else NaN. */
function vLength(heads, name, v) {
    if (heads === null || v === null || heads.length !== 1) return NaN;
    const r = heads[0];
    if (r.name !== name || !Number.isInteger(r.len) || !Number.isInteger(r.pos)) return NaN;
    return r.pos >= v[0] && r.pos < v[1] ? r.len : NaN;
}

/** Names whose length is not a finite number <= budget (fail closed). */
function overBudget(lengths, budget) {
    const over = [];
    for (const name of Object.keys(lengths)) {
        const n = lengths[name];
        if (!Number.isFinite(budget) || !Number.isFinite(n) || !(n <= budget)) over.push(name);
    }
    return over;
}

/** Names whose length differs from the pin (a missing / NaN length differs). */
function pinMismatch(lengths, pin) {
    const bad = [];
    for (const name of Object.keys(pin)) if (lengths[name] !== pin[name]) bad.push(name);
    return bad;
}

function runChild(args, input) {
    return new Promise((resolve) => {
        const cp = execFile(process.execPath, args, {
            encoding: 'utf8', timeout: CHILD_MS, killSignal: 'SIGKILL', maxBuffer: 1 << 26,
        }, (err, stdout, stderr) => {
            resolve({
                error: err ? String(err.message) + (err.signal ? ' signal ' + err.signal : '') +
                    ' | stderr: ' + String(stderr).slice(0, 2048) : null,
                stdout,
            });
        });
        if (input !== undefined) cp.stdin.end(input);
        else cp.stdin.end();
    });
}

function bytecodeChild(name, srcArg, mode, input) {
    return runChild(['--print-bytecode', '--print-bytecode-filter=' + name, '--input-type=module',
        '-e', DRIVER, srcArg, mode], input);
}

// --- all children start now, in parallel ---------------------------------------

const PAD_COUNT = SRC.split(PAD_FROM).length - 1;
const PADDED = PAD_COUNT === 1 ? SRC.replace(PAD_FROM, () => PAD_TO) : null;
const BC = new Map();
for (const name of NAMES) BC.set(name, bytecodeChild(name, SRC_URL, 'veb'));
const PAD_JOB = PADDED === null ? null : bytecodeChild('has', '-', 'veb', PADDED);
const BOTH_JOB = bytecodeChild('has', SRC_URL, 'both');
const V8_KEY = process.versions.v8.split('.').slice(0, 2).join('.');

async function childOut(job, label) {
    const r = await job;
    assert.equal(r.error, null, label + ' child: ' + r.error);
    assert.ok(DONE.exec(r.stdout) !== null, label + ': driver did not reach its done marker');
    return r.stdout;
}

async function measure() {
    const v = regionOf(SRC, V_MARKER);
    assert.ok(v !== null, 'vEBTree marker missing or doubled in LogLogN.js');
    const lengths = {};
    for (const name of NAMES) {
        const heads = parseHeaders(await childOut(BC.get(name), name));
        assert.ok(heads !== null, name + ': a bytecode header without a length or a position');
        const n = vLength(heads, name, v);
        assert.ok(Number.isInteger(n) && n > 0, name + ': not exactly one header, inside the vEB region [' +
            v[0] + ', ' + v[1] + '): ' + JSON.stringify(heads));
        lengths[name] = n;
    }
    assert.equal(Object.keys(lengths).length, NAMES.length, 'coverage floor: all 7 names measured');
    return lengths;
}
const MEASURED = measure();

// --- gate ------------------------------------------------------------------------

test('G2-7 each vEBTree hot method has exactly one header, in the vEB region', T, async (t) => {
    const lengths = await MEASURED;
    t.diagnostic('V8 ' + process.versions.v8 + ' ' + JSON.stringify(lengths));
});

test('G2-7 delete / successor / predecessor are > 460 B on any V8 (never inlined, C-11)', T, async () => {
    const lengths = await MEASURED;
    const small = NEVER_INLINED.filter((n) => !(lengths[n] > BUDGET));
    assert.deepEqual(small, [], 'unexpectedly inlinable: ' + JSON.stringify(lengths));
});

test('G2-7 exact size pins for this V8 major.minor (fail closed if unpinned)', T, async () => {
    const pin = PINS[V8_KEY];
    assert.ok(pin !== undefined, 'no size pins for V8 ' + process.versions.v8 +
        ' (key ' + V8_KEY + '): re-measure and add a PINS row');
    const lengths = await MEASURED;
    assert.deepEqual(pinMismatch(lengths, pin), [], 'size differs from pin ' + JSON.stringify(pin) +
        ': ' + JSON.stringify(lengths));
});

// --- must-fail controls ----------------------------------------------------------

test('G2-7 control: a padded vEBTree#has flips the pin (size != 218, > 218), found in the vEB region', T, async (t) => {
    assert.equal(PAD_COUNT, 1, 'pad anchor must occur exactly once in LogLogN.js');
    const v = regionOf(PADDED, V_MARKER);
    assert.ok(v !== null);
    const heads = parseHeaders(await childOut(PAD_JOB, 'padded has'));
    const n = vLength(heads, 'has', v);
    assert.ok(Number.isInteger(n), 'padded has not found exactly once in the vEB region');
    t.diagnostic('padded has=' + n);
    assert.ok(n > PINS['14.6'].has, 'padded has ' + n + ' must exceed 218');
    assert.deepEqual(pinMismatch({ has: n }, { has: PINS['14.6'].has }), ['has'], 'the pin must flip');
});

test('G2-7 control: also calling StratifiedBitset#has puts a header outside the vEB region', T, async () => {
    const v = regionOf(SRC, V_MARKER);
    const heads = parseHeaders(await childOut(BOTH_JOB, 'both'));
    assert.ok(heads !== null);
    assert.equal(heads.length, 2, 'both drivers must compile two has bodies');
    const outside = heads.filter((r) => !(r.pos >= v[0] && r.pos < v[1]));
    assert.equal(outside.length, 1, 'StratifiedBitset#has must sit outside the vEB region');
    assert.ok(Number.isNaN(vLength(heads, 'has', v)), 'a header outside the region must not parse');
});

test('G2-7 control: parser, pin and budget fail closed', T, () => {
    const row = (name, len, pos) => HEAD + name + ' (0x1 <SharedFunctionInfo ' + name + '>)]\n' +
        'Bytecode length: ' + len + '\nParameter count 2\n  ' + pos + ' S> 0x1 @    0 : 0b 03             Ldar a0\n';
    const V = [1000, 2000];
    assert.deepEqual(parseHeaders(row('has', 218, 1500)), [{ name: 'has', len: 218, pos: 1500 }]);
    assert.equal(vLength(parseHeaders(row('has', 218, 1500)), 'has', V), 218, 'good');
    assert.equal(vLength(parseHeaders(row('has', 120, 1000)), 'has', V), 120, 'at region start');
    assert.deepEqual(parseHeaders(''), []);
    assert.ok(Number.isNaN(vLength(parseHeaders(''), 'has', V)), 'missing header');
    assert.ok(Number.isNaN(vLength(parseHeaders(row('has', 1, 1500) + row('has', 2, 1600)), 'has', V)), 'doubled');
    const noLen = row('has', 120, 1500).replace('Bytecode length: 120\n', '');
    assert.equal(parseHeaders(noLen), null, 'header with no size');
    assert.equal(parseHeaders(row('has', 1, 1500) + noLen), null, 'one unparseable header poisons the parse');
    assert.equal(parseHeaders(row('has', 120, 1500).replace(' S> ', ' E> ')), null, 'no position');
    assert.equal(parseHeaders(row('has', 'NaN', 1500)), null, 'non-numeric size');
    assert.ok(Number.isNaN(vLength(parseHeaders(row('has', 120, 1500)), 'add', V)), 'wrong name');
    assert.ok(Number.isNaN(vLength(parseHeaders(row('has', 120, 500)), 'has', V)), 'below region');
    assert.ok(Number.isNaN(vLength(parseHeaders(row('has', 120, 2000)), 'has', V)), 'position at region end');
    assert.ok(Number.isNaN(vLength(parseHeaders(row('has', 120, 1500)), 'has', null)), 'null region');
    assert.ok(Number.isNaN(vLength(null, 'has', V)), 'null parse');
    assert.deepEqual(overBudget({ has: 460, add: 461, min: NaN }, BUDGET), ['add', 'min']);
    assert.deepEqual(overBudget({ has: 1 }, NaN), ['has']);
    assert.deepEqual(pinMismatch({ has: 219 }, { has: 218 }), ['has']);
    assert.deepEqual(pinMismatch({}, { has: 218 }), ['has'], 'missing length differs from pin');
    assert.deepEqual(pinMismatch({ has: NaN }, { has: 218 }), ['has']);
    assert.deepEqual(pinMismatch({ has: 218 }, { has: 218 }), []);
    assert.equal(regionOf('x', V_MARKER), null);
    assert.equal(regionOf(V_MARKER + V_MARKER, V_MARKER), null);
    assert.deepEqual(regionOf('a' + V_MARKER + ' b', V_MARKER), [1, 1 + V_MARKER.length + 2], 'marker -> EOF');
});
