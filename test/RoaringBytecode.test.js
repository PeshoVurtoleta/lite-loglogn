    assert.equal(rLength(parseHeaders(row('has', 452, 1500)), 'has', R), 452, 'good');
    assert.equal(rLength(parseHeaders(row('_bmpNextGEQ', 363, 1000)), '_bmpNextGEQ', R), 363, 'at region start');
    assert.deepEqual(parseHeaders(''), []);
    assert.ok(Number.isNaN(rLength(parseHeaders(''), 'has', R)), 'missing header');
    assert.ok(Number.isNaN(rLength(parseHeaders(row('has', 1, 1500) + row('has', 2, 1600)), 'has', R)), 'doubled');
    const noLen = row('has', 120, 1500).replace('Bytecode length: 120\n', '');
    assert.equal(parseHeaders(noLen), null, 'header with no size');
    assert.equal(parseHeaders(row('has', 1, 1500) + noLen), null, 'one unparseable header poisons the parse');
    assert.equal(parseHeaders(row('has', 120, 1500).replace(' S> ', ' E> ')), null, 'no position');
    assert.equal(parseHeaders(row('has', 'NaN', 1500)), null, 'non-numeric size');
    assert.ok(Number.isNaN(rLength(parseHeaders(row('has', 120, 1500)), 'add', R)), 'wrong name');
    assert.ok(Number.isNaN(rLength(parseHeaders(row('has', 120, 500)), 'has', R)), 'below region');
    assert.ok(Number.isNaN(rLength(parseHeaders(row('has', 120, 2000)), 'has', R)), 'position at region end');
    assert.ok(Number.isNaN(rLength(parseHeaders(row('has', 120, 1500)), 'has', null)), 'null region');
    assert.ok(Number.isNaN(rLength(null, 'has', R)), 'null parse');
    assert.deepEqual(overBudget({ has: 460, add: 461, min: NaN }, BUDGET), ['add', 'min']);
    assert.deepEqual(overBudget({ has: 1 }, NaN), ['has']);
    assert.deepEqual(notOver({ add: 461, delete: 460, successor: NaN }, BUDGET), ['delete', 'successor']);
    assert.deepEqual(notOver({ add: 900 }, NaN), ['add']);
    assert.deepEqual(pinMismatch({ has: 453 }, { has: 452 }), ['has']);
    assert.deepEqual(pinMismatch({}, { has: 452 }), ['has'], 'missing length differs from pin');
    assert.deepEqual(pinMismatch({ has: NaN }, { has: 452 }), ['has']);
    assert.deepEqual(pinMismatch({ has: 452 }, { has: 452 }), []);
    assert.equal(mutate('a b a', 'a', 'c'), null, 'doubled anchor');
    assert.equal(mutate('b', 'a', 'c'), null, 'missing anchor');
    assert.equal(mutate('a$&b', '$&', 'x'), 'axb', 'replacement taken literally');
    const flag = (name, v) => '  ' + name + ' (some help text)\n        type: int  default: ' + name + '=' + v + '\n';
    const MAX = '--max-maglev-inlined-bytecode-size';
    assert.equal(maglevLimit(flag(MAX, 100)), 100, 'good');
    assert.equal(maglevLimit(flag(MAX + '-cumulative', 920) + flag(MAX, 100) + flag(MAX + '-small', 27)), 100, 'among its siblings');
    assert.ok(Number.isNaN(maglevLimit(flag(MAX + '-cumulative', 920))), 'only a sibling flag');
    assert.ok(Number.isNaN(maglevLimit('')), 'no line');
    assert.ok(Number.isNaN(maglevLimit(flag(MAX, 'x'))), 'non-numeric default');
    assert.equal(regionOf('x', R_MARKER), null);
    assert.equal(regionOf(R_MARKER + R_MARKER, R_MARKER), null);
    assert.deepEqual(regionOf('a' + R_MARKER + ' b', R_MARKER), [1, 1 + R_MARKER.length + 2], 'marker -> EOF');
    assert.equal(regionOf('a' + R_MARKER + ' b\n// --- Next (0.7.0)\nc', R_MARKER), null,
        'a banner after the RoaringSet marker fails closed');
