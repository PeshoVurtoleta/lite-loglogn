// --- helpers (pure; unit-tested below) ------------------------------------------

/** [start, EOF) for the marker; null if the marker is missing / doubled or ANY banner follows it (fail closed). */
function regionOf(text, marker) {
    const a = text.indexOf(marker);
    if (a < 0 || text.indexOf(marker, a + 1) >= 0) return null;
    if (text.indexOf('\n// --- ', a + 1) >= 0) return null;
    return [a, text.length];
}

/** Every header as { name, len, pos }; null if ANY header lacks a length or a position. */
function parseHeaders(text) {
    const blocks = text.split(HEAD);
    const out = [];
    for (let i = 1; i < blocks.length; i++) {
        const h = /^(\S*) [^\]\n]*\]\s*\nBytecode length: (\d+)\n/.exec(blocks[i]);
        const p = /^\s*(\d+) S> /m.exec(blocks[i]);
        if (h === null || p === null) return null;
        out.push({ name: h[1], len: Number(h[2]), pos: Number(p[1]) });
    }
    return out;
}

/** Length of the ONE header named `name`, inside region r; else NaN. */
function rLength(heads, name, r) {
    if (heads === null || r === null || heads.length !== 1) return NaN;
    const h = heads[0];
    if (h.name !== name || !Number.isInteger(h.len) || !Number.isInteger(h.pos)) return NaN;
    return h.pos >= r[0] && h.pos < r[1] ? h.len : NaN;
}

/** Names whose length is not a finite number <= budget (fail closed). */
function overBudget(lengths, budget) {
    const over = [];
    for (const name of Object.keys(lengths)) {
        const n = lengths[name];
        if (!Number.isFinite(budget) || !Number.isFinite(n) || !(n <= budget)) over.push(name);
    }
    return over;
}

/** Names whose length is not a finite number > budget (fail closed). */
function notOver(lengths, budget) {
    const bad = [];
    for (const name of Object.keys(lengths)) {
        const n = lengths[name];
        if (!Number.isFinite(budget) || !Number.isFinite(n) || !(n > budget)) bad.push(name);
    }
    return bad;
}

/** Names whose length differs from the pin (a missing / NaN length differs). */
function pinMismatch(lengths, pin) {
    const bad = [];
    for (const name of Object.keys(pin)) if (lengths[name] !== pin[name]) bad.push(name);
    return bad;
}

/** The default of --max-maglev-inlined-bytecode-size in a `node --v8-options` dump; NaN if absent (fail closed). */
function maglevLimit(text) {
    const m = MAGLEV_LINE.exec(text);
    return m === null ? NaN : Number(m[1]);
}

/** The text with `from` replaced by `to`, or null unless `from` occurs exactly once. */
function mutate(text, from, to) {
    if (text.split(from).length - 1 !== 1) return null;
    return text.replace(from, () => to);
}

let running = 0;
const queue = [];
function runChild(args) {
    return new Promise((resolve) => {
        const go = () => {
            running++;
            execFile(process.execPath, args, {
                encoding: 'utf8', timeout: CHILD_MS, killSignal: 'SIGKILL', maxBuffer: 1 << 26,
            }, (err, stdout, stderr) => {
                running--;
                const next = queue.shift();
                if (next !== undefined) next();
                resolve({
                    error: err ? String(err.message) + (err.signal ? ' signal ' + err.signal : '') +
                        ' | stderr: ' + String(stderr).slice(0, 2048) : null,
                    stdout,
                });
            }).stdin.end();
        };
        if (running < CAP) go();
        else queue.push(go);
    });
}

function bytecodeChild(name, url, mode) {
    return runChild(['--print-bytecode', '--print-bytecode-filter=' + name, '--input-type=module',
        '-e', DRIVER, url, mode]);
}

